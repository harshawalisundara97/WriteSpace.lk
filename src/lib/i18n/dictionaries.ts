const DICTS: Record<Locale, Messages> = { en, si, ta };

/** Translate with English fallback. `{name}` placeholders are filled from vars. */
export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const s = DICTS[locale][key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

export function messagesFor(locale: Locale): Record<MessageKey, string> {
  return { ...en, ...DICTS[locale] } as Record<MessageKey, string>;
}
